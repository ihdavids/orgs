#!/usr/bin/env python3
"""Lift the character sheet's casting effects out for worg.

The html character sheet (templates/dnd_character_html.tpl) carries a whole
effects engine in its dice tray script: the 3d dice board, every element a
damage type or a spell puts on the table (fire, frost, lightning, the blast,
the mage hand, the panther...), the spell-school flourishes and their sounds.
worg's DM screen plays the same effects over a map. Rather than a second copy
to drift, this slices those sections out of the template by the comment lines
that open them and wraps them as one script, worg/public/dicefx.js, which
exposes window.OrgsFx. tools/buildworg.sh runs it before every worg build.

A section is from its opening marker up to (not including) the next marker
named. If the template's sections are renamed this fails loudly rather than
writing half an engine.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, '..', '..'))
TPL = os.path.join(REPO, 'templates', 'dnd_character_html.tpl')

SECTIONS = [
    # (first line contains, stop at the line containing)
    ('  // ------------------------------------------------------------------ maths',
     '  // --------------------------------------------------------- landing zones'),
    ('  // -------------------------------------------------------- spell flourish',
     '  // ------------------------------------------------------------ coin spill'),
    ('  // ------------------------------------------------------------------ sound',
     '  // ------------------------------------------------------------------- mood'),
]

WRAP_HEAD = """// GENERATED by orgs tools/dicefx/extract.py from templates/dnd_character_html.tpl.
// Do not edit: change the character sheet and build worg again.
//
// The sheet's dice board, elements, spell flourishes and their sounds, for
// worg's map screens (src/fx.ts). window.OrgsFx is the way in.
(function () {
  'use strict';
  // The sheet dims its full-screen flashes for reduced motion; over a map the
  // effects are asked for one by one, so they play as they are.
  var FLASH_OFF = false;
"""

WRAP_TAIL = """
  // ---------------------------------------------------------------- the way in
  var VOICES = [
    ['Fire crackling', function () { crackle(); }], ['Wave', function () { wash(); }], ['Choir', function () { choir(); }],
    ['Rumble', function () { rumble(); }], ['Thunder', function () { thunder(1); }], ['Howling wind', function () { howl(); }],
    ['Murmuring voices', function () { murmur(); }], ['Whoosh', function () { whoosh(); }], ['Rope creaking', function () { creak('twist'); }],
    ['Chains rattling', function () { creak('links'); }], ['Branches creaking', function () { creak('leaves'); }], ['Cheering crowd', function () { cheer(); }],
    ['Dirge', function () { dirge(); }], ['Coins', function () { clink(0.9); }], ['Pop', function () { pop(0.9); }],
    ['Steel and blood', function () { stab(); }], ['Knock', function () { knock(0.9, 520); }], ['Tick', function () { tick(0.8); }]
  ];
  var boards = [];
  function boardOn(canvas) {
    for (var i = 0; i < boards.length; i++) { if (boards[i].canvas === canvas) { return boards[i]; } }
    var b = new DiceBoard(canvas);
    boards.push(b);
    return b;
  }
  var flourishes = [];
  function flourishOn(canvas) {
    for (var i = 0; i < flourishes.length; i++) { if (flourishes[i].canvas === canvas) { return flourishes[i]; } }
    var b = new SpellBoard(canvas);
    flourishes.push(b);
    return b;
  }
  try { soundLoad(); } catch (e) { /* sound stays as it was */ }
  window.OrgsFx = {
    // Every element the sheet can put on the table.
    elements: Object.keys(ELEMENTS).filter(function (k) { return k.indexOf('old') !== 0; }),
    schools: SCHOOLS ? Object.keys(SCHOOLS) : [],
    // Play an element at a point of the canvas (css pixels of the window).
    element: function (canvas, element, x, y, tint) {
      var b = boardOn(canvas);
      b.table = { l: 0, t: 0, r: window.innerWidth, b: window.innerHeight };
      b.elsewhere(element, { x: x, y: y }, tint);
    },
    // A school of magic's flourish at a point.
    flourish: function (canvas, school, x, y, size) {
      flourishOn(canvas).cast(school, { x: x, y: y }, size || 1.4);
    },
    sound: function (on) { if (typeof on === 'boolean') { SOUND.on = on; } return SOUND.on; },
    // The sheet's sounds by name, each on its own, for the DM screen's sound
    // board; how loud they are, 0..1 (the sheet's own level is 1).
    voices: VOICES.map(function (v) { return v[0]; }),
    voice: function (name) {
      for (var i = 0; i < VOICES.length; i++) {
        if (VOICES[i][0] === name) {
          var was = SOUND.on;
          SOUND.on = true;
          try { VOICES[i][1](); } catch (e) { /* audio is a nicety */ }
          SOUND.on = was;
          return true;
        }
      }
      return false;
    },
    volume: function (v) {
      var ctx = audio();
      if (ctx && SOUND.gain && typeof v === 'number') { SOUND.gain.gain.value = 0.34 * Math.max(0, Math.min(2, v)); }
    }
  };
})();
"""


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(REPO, '..', 'worg', 'public', 'dicefx.js')
    with open(TPL, encoding='utf-8') as f:
        lines = f.read().split('\n')
    body = []
    for start, stop in SECTIONS:
        try:
            a = next(i for i, l in enumerate(lines) if l.rstrip() == start)
            b = next(i for i, l in enumerate(lines) if i > a and l.rstrip() == stop)
        except StopIteration:
            sys.exit('dicefx: the sheet has no section %r (up to %r) - was it renamed?' % (start.strip(), stop.strip()))
        chunk = lines[a:b]
        if any('{{' in l or '{%' in l for l in chunk):
            sys.exit('dicefx: section %r has template tags in it; it cannot be lifted as plain script' % start.strip())
        body.extend(chunk)
    with open(out, 'w', encoding='utf-8') as f:
        f.write(WRAP_HEAD + '\n'.join(body) + WRAP_TAIL)
    print('dicefx: %d lines into %s' % (len(body), out))


if __name__ == '__main__':
    main()
